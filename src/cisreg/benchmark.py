"""Timing of brute-force and bounding-box-tree closest-point search.

Usage:
    python -m cisreg.benchmark [--out results/search_timing.md]

Each timing is the best of several repeats (time.perf_counter). The same run
also checks that the two searches return the same distances.

Author: Parmida Mazloomi
"""

from __future__ import annotations

import argparse
import platform
import time
from pathlib import Path

import numpy as np

from cisreg import datasets
from cisreg.boxtree import BoundingBoxTree
from cisreg.fileio import read_mesh
from cisreg.search import BruteForceSearch
from cisreg.tracking import pointer_tips


def best_time(fn, repeats: int = 3) -> float:
    times = []
    for _ in range(repeats):
        start = time.perf_counter()
        fn()
        times.append(time.perf_counter() - start)
    return min(times)


def run(data_dir: Path, seed: int = 0) -> str:
    mesh = read_mesh(datasets.mesh_path(data_dir, "PA3"))
    brute = BruteForceSearch(mesh)
    build = best_time(lambda: BoundingBoxTree(mesh))
    tree = BoundingBoxTree(mesh)

    rows = []
    worst = 0.0

    def measure(name: str, queries: np.ndarray, hint=None) -> None:
        nonlocal worst
        t_brute = best_time(lambda: brute.closest_points(queries))
        t_tree = best_time(lambda: tree.closest_points(queries, hint=hint))
        slow = brute.closest_points(queries)
        fast = tree.closest_points(queries, hint=hint)
        worst = max(worst, float(np.max(np.abs(fast.distances - slow.distances))))
        checks = tree.triangle_checks / len(queries)
        rows.append(
            f"| {name} | {len(queries)} | {1e3 * t_brute:.1f} | {1e3 * t_tree:.1f} "
            f"| {t_brute / t_tree:.1f} | {checks:.0f} |"
        )

    for assignment in ("PA3", "PA4", "PA5"):
        tips = []
        for label in datasets.list_sets(data_dir, assignment):
            inputs = datasets.load_inputs(data_dir, assignment, label)
            tips.append(pointer_tips(inputs.body_a, inputs.body_b, inputs.samples))
        measure(f"{assignment} pointer tips, all sets", np.vstack(tips))

    rng = np.random.default_rng(seed)
    lo, hi = mesh.vertices.min(axis=0) - 10, mesh.vertices.max(axis=0) + 10
    for n in (1, 10, 100, 1000):
        measure(f"random points near the bone, N = {n}", rng.uniform(lo, hi, size=(n, 3)))

    queries = rng.uniform(lo, hi, size=(200, 3))
    previous = brute.closest_points(queries - rng.normal(scale=0.5, size=queries.shape))
    measure("random, hint = match of a nearby point (as in ICP)", queries, hint=previous.triangles)

    header = [
        "# Closest-point search timing",
        "",
        "Generated by `python -m cisreg.benchmark`. Times are the best of 3 runs, in milliseconds,",
        f"on {platform.machine()} with Python {platform.python_version()} and NumPy {np.__version__}.",
        f"The mesh has {mesh.n_triangles} triangles. The tree has {tree.n_nodes} nodes,",
        f"depth {tree.depth()}, at most {tree.leaf_size} triangles per leaf, and builds in",
        f"{1e3 * build:.1f} ms.",
        "",
        "\"Tests per query\" is the number of exact point-to-triangle tests the tree needed per",
        f"query point; brute force always does {mesh.n_triangles}.",
        "",
        "| Queries | N | Brute force (ms) | Tree (ms) | Speedup | Tests per query |",
        "|---|---|---|---|---|---|",
    ]
    footer = [
        "",
        f"Largest difference between the two searches' distances over all rows: {worst:.1e} mm.",
        "",
        "The pointer tips lie within a few millimetres of the surface, so the seeded bound is",
        "small and only a handful of leaf boxes stay in play. Random points in the bounding box",
        "of the bone are often deep inside it or far outside, where the bound is large and more",
        "boxes overlap the search sphere, so more triangles must be tested. A hint from a nearby",
        "earlier match gives a tight bound from the start, which is the situation in every ICP",
        "iteration after the first. For a single query the tree's fixed cost of about 1 ms of",
        "NumPy calls dominates; the advantage grows with the batch size because each tree level",
        "is processed for all queries in one vectorized step.",
        "",
    ]
    return "\n".join(header + rows + footer)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data-dir", type=Path, default=datasets.DEFAULT_DATA_DIR)
    parser.add_argument("--out", type=Path, default=Path("results/search_timing.md"))
    args = parser.parse_args(argv)
    text = run(args.data_dir)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
